"""Create a .env.example from a .env, without copying any values."""

from __future__ import annotations

import re

from .parser import parse
from .rules import _valid_url

_INT = re.compile(r"[+-]?\d+")
_FLOAT = re.compile(r"[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?")
HEADER = "# Generated by envguard. Values are intentionally blank: fill in your own.\n"


def infer(key: str, value: str):
    """Guess a directive from a value (only the *kind* is used, never the value)."""
    if value == "":
        return "optional"
    if value.lower() in ("true", "false"):
        return "bool"
    if _INT.fullmatch(value):
        if key.upper().endswith("PORT") and 1 <= int(value) <= 65535:
            return "port"
        return "int"
    if _FLOAT.fullmatch(value):
        return "float"
    if "://" in value and _valid_url(value):
        return "url"
    return None


def generate(env_text: str):
    """Return ``(example_text, variable_count)``."""
    entries = {}
    for entry in parse(env_text).entries:
        entries[entry.key] = entry  # last definition wins, first position is kept
    lines = [HEADER]
    for key, entry in entries.items():
        directive = infer(key, entry.value)
        if directive:
            lines.append(f"# envguard: {directive}")
        lines.append(f"{key}=")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n", len(entries)
